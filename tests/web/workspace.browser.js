async page => {
  if (new URL(page.url()).origin !== 'http://127.0.0.1:3000') throw new Error('Disposable loopback fixture required');
  await page.setViewportSize({width:1440,height:1000});
  page.on('dialog',dialog=>dialog.accept(dialog.type()==='prompt'?'owner':undefined));
  await page.getByRole('button',{name:'Login fixture lokal',exact:true}).click();
  await page.getByLabel('Organisasi',{exact:true}).waitFor();
  const organization=await page.getByLabel('Organisasi',{exact:true}).locator('option').nth(1).getAttribute('value');
  if(!organization)throw new Error('Fixture Owner bootstrap failed');
  await page.getByLabel('Organisasi',{exact:true}).selectOption(organization);
  await page.getByRole('button',{name:'Workspace baru',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('[aria-label="Workspace"]')?.options.length>1);
  const workspace=await page.getByLabel('Workspace',{exact:true}).locator('option').last().getAttribute('value');
  await page.getByLabel('Workspace',{exact:true}).selectOption(workspace);
  const terminal=async status=>page.waitForFunction(status=>document.querySelector('.execution-status')?.textContent===status,status,{timeout:30000});
  const edit=async sql=>{
    const input=page.locator('.monaco-editor textarea.inputarea').first();
    await input.click();await input.press('ControlOrMeta+A');await input.pressSequentially(sql);
  };
  for(const engine of ['Postgres','MySql']) {
    await page.getByRole('button',{name:/Koneksi baru/}).click();
    const dialog=page.getByRole('dialog');
    await dialog.getByLabel('Nama',{exact:true}).fill(`Browser ${engine}`);
    await dialog.getByLabel('Database engine',{exact:true}).selectOption(engine);
    await dialog.getByLabel('Host',{exact:true}).fill('127.0.0.1');
    await dialog.getByLabel('Port',{exact:true}).fill(engine==='Postgres'?'55432':'53306');
    await dialog.getByLabel('Username',{exact:true}).fill('studio');
    await dialog.getByLabel('Database',{exact:true}).fill('studio_test');
    await dialog.getByLabel('Password',{exact:true}).fill('studio_test');
    await dialog.getByLabel('TLS',{exact:true}).selectOption('disable');
    await dialog.getByLabel(/Simpan history SQL/).check();
    await dialog.getByRole('button',{name:'Test koneksi',exact:true}).click();
    await page.getByText('Koneksi berhasil.',{exact:true}).waitFor();
    await dialog.getByRole('button',{name:'Simpan koneksi',exact:true}).click();
    await dialog.waitFor({state:'hidden'});
    await page.getByText(`Browser ${engine}`,{exact:true}).first().click();
    await page.getByRole('button',{name:'Connect',exact:true}).click();
    await page.locator('.explorer-tree').waitFor();
    await page.locator('.monaco-editor').waitFor();
    await edit(engine==='Postgres'?'SELECT CAST(9007199254740993 AS BIGINT) AS precise, NULL AS empty_value':'SELECT CAST(9007199254740993 AS SIGNED) AS precise, NULL AS empty_value');
    await page.getByRole('button',{name:'Run',exact:true}).click();await terminal('Completed');
    await page.getByRole('grid').getByText('9007199254740993',{exact:true}).first().waitFor();
    await page.getByLabel('Auto Commit',{exact:true}).uncheck();
    await page.waitForFunction(()=>document.querySelector('.commit-mode input')?.checked===false);
    await edit('SELECT 1');await page.getByRole('button',{name:'Run',exact:true}).click();await terminal('Completed');
    await page.waitForFunction(()=>document.querySelector('.editor-context')?.textContent.includes('Active'));
    await page.getByRole('button',{name:'Rollback',exact:true}).click();await terminal('Completed');
    await page.waitForFunction(()=>document.querySelector('.editor-context')?.textContent.includes('Idle'));
    await edit(engine==='Postgres'?'SELECT pg_sleep(5)':'SELECT SLEEP(5)');
    await page.getByRole('button',{name:'Run',exact:true}).click();
    await page.getByRole('button',{name:'Cancel',exact:true}).click();await terminal('Cancelled');
    await page.getByRole('button',{name:'Rollback',exact:true}).click();await terminal('Completed');
    await page.screenshot({path:`test-results/web/${engine}.png`});
    await page.getByRole('button',{name:'History',exact:true}).click();
    await page.getByRole('heading',{name:'Query history',exact:true}).waitFor();
    if(await page.locator('.document-line').count()===0)throw new Error('Opt-in history missing');
    await page.getByRole('button',{name:'Kembali ke editor',exact:true}).click();
    await page.getByLabel('Auto Commit',{exact:true}).check();
    const table=`a_browser_edit_${Date.now()}`;
    await edit(`CREATE TABLE ${table} (id BIGINT PRIMARY KEY,label VARCHAR(80) DEFAULT 'default'); INSERT INTO ${table} VALUES(1,'original')`);
    await page.getByRole('button',{name:'Run script',exact:true}).click();await terminal('Completed');
    await page.getByLabel('Refresh metadata',{exact:true}).click();
    if(engine==='Postgres') await page.locator('.schema-line').filter({hasText:'public'}).click();
    const group=page.locator('.tree-group > button').filter({hasText:'Tables'}).first();
    if(await group.getAttribute('aria-expanded')!=='true')await group.click();
    await page.locator(`.tree-object[title="${table}"]`).click();
    await page.locator('.inspector-tabs').getByRole('button',{name:'Edit',exact:true}).click();
    const editor=page.locator('.table-editor');
    await editor.getByLabel('label baris 1',{exact:true}).waitFor();
    const apply=async()=>{
      await editor.getByRole('button',{name:'Preview',exact:true}).click();
      await editor.locator('pre').waitFor();
      page.once('dialog',dialog=>dialog.accept());
      await editor.getByRole('button',{name:'Apply',exact:true}).click();
      await page.waitForFunction(()=>document.querySelector('.table-editor .table-controls')?.textContent.includes('0/100 perubahan · Applied'),null,{timeout:30000});
    };
    await editor.getByLabel('label baris 1',{exact:true}).fill('changed');await apply();
    await page.waitForFunction(()=>document.querySelector('[aria-label="label baris 1"]')?.value==='changed');
    if(!(await editor.locator('tbody tr').first().textContent()).includes('1'))throw new Error('Original PK missing');
    await editor.getByRole('button',{name:'Tambah baris',exact:true}).click();
    await editor.getByLabel('id baru 1',{exact:true}).fill('2');await apply();
    await editor.getByLabel('label baris 2',{exact:true}).waitFor();
    if(await editor.getByLabel('label baris 2',{exact:true}).inputValue()!=='default')throw new Error('DEFAULT readback missing');
    await editor.locator('tbody tr').first().getByRole('button',{name:'NULL',exact:true}).click();await apply();
    await page.waitForFunction(()=>document.querySelector('[aria-label="label baris 1"]')?.placeholder==='NULL');
    await editor.getByRole('button',{name:'Hapus',exact:true}).first().click();await apply();
    await page.waitForFunction(()=>document.querySelectorAll('.table-editor tbody tr').length===1);
    await page.getByLabel('Tab SQL baru',{exact:true}).click();
    await edit(`DROP TABLE ${table}`);await page.getByRole('button',{name:'Run',exact:true}).click();await terminal('Completed');

  }
  await page.getByRole('button',{name:'Logout',exact:true}).click();
  await page.getByRole('button',{name:'Login fixture lokal',exact:true}).waitFor();
  return 'phase4-web-fixture-pass';
}
